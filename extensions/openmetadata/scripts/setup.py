"""Create this extension's .env next to the handshake file the platform wrote (.env.bridge).

Standard library only: the platform's installer may run it in the platform image.
OpenMetadata settings already in .env (OM_URL, OM_JWT_TOKEN, ...) are kept on reruns.
"""

import os
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
DEFAULTS = {"OM_URL": "", "OM_JWT_TOKEN": "", "OM_SERVICE_PREFIX": "iceberg", "OM_DOMAIN": "Iceberg Data Platform"}


def read(path):
    values = {}
    for line in path.read_text().splitlines():
        key, sep, value = line.partition("=")
        if sep and not key.startswith("#"):
            values[key.strip()] = value.strip()
    return values


def setup(root=ROOT):
    bridge = root / ".env.bridge"
    if not bridge.exists():
        raise SystemExit(
            "No .env.bridge. Register the extension with the platform first, from the platform directory:\n"
            "  uv run python -m scripts.setup --extension openmetadata --origin http://localhost:3011 "
            "--handshake extensions/openmetadata/.env.bridge --listing")
    handshake = read(bridge)
    if handshake.get("BRIDGE_CONTRACT") != "1":
        raise SystemExit("This OpenMetadata extension needs a Bridge v1 handshake file.")
    config = root / ".env"
    values = read(config) if config.exists() else {}
    for key, value in DEFAULTS.items():
        values.setdefault(key, value)
    origin = urlsplit(handshake["EXTENSION_ORIGIN"])
    values["PLATFORM_NETWORK"] = handshake["PLATFORM_NETWORK"]
    values["OM_PORT"] = str(origin.port or (443 if origin.scheme == "https" else 80))
    content = "".join(f"{k}={v}\n" for k, v in values.items())
    if config.exists():
        config.unlink()
    with os.fdopen(os.open(config, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600), "w") as file:
        file.write("# Generated by scripts.setup; the bridge credentials stay in .env.bridge.\n" + content)
    if not values["OM_URL"] or not values["OM_JWT_TOKEN"]:
        print("Set OM_URL (such as http://openmetadata-server:8585/api) and OM_JWT_TOKEN (the JWT of an "
              "OpenMetadata bot) in .env.")
    print("Then build and start the extension:\n  docker compose up -d --build --wait")


if __name__ == "__main__":
    setup()
