"""Create this extension's .env next to the handshake file the platform wrote (.env.bridge).

Standard library only: the extension's installer runs it in the platform image.
OpenMetadata settings already in .env (OM_URL, OM_JWT_TOKEN, ...) are kept on reruns. Settings in the
environment replace them; in a terminal the setup asks for the ones still missing.

  uv run python -m scripts.setup           # your own OpenMetadata
  uv run python -m scripts.setup --demo    # the local OpenMetadata of compose.openmetadata.yaml
"""

import argparse
import getpass
import os
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
DEFAULTS = {"OM_URL": "", "OM_JWT_TOKEN": "", "OM_SERVICE_PREFIX": "iceberg", "OM_DOMAIN": "Iceberg Data Platform"}
# Variables the setup takes from the environment; the installer passes the same names.
PASSTHROUGH = ("OM_URL", "OM_JWT_TOKEN", "OM_UI_URL")
# With COMPOSE_FILE in .env, `docker compose` in this folder always includes the local OpenMetadata.
DEMO_COMPOSE = "compose.yaml:compose.openmetadata.yaml"


def read(path):
    values = {}
    for line in path.read_text().splitlines():
        key, sep, value = line.partition("=")
        if sep and not key.startswith("#"):
            values[key.strip()] = value.strip()
    return values


def url(text):
    if text and urlsplit(text).scheme not in ("http", "https"):
        raise SystemExit(f"Not an http(s) address: {text}")
    return text.rstrip("/")


def ask_missing(values, ask, prompt):
    if not values.get("OM_URL"):
        values["OM_URL"] = url(prompt(
            "OpenMetadata API address, as the extension's container reaches it\n"
            "  (such as https://metadata.example.com/api): ").strip())
    if not values.get("OM_JWT_TOKEN"):
        values["OM_JWT_TOKEN"] = ask(
            "JWT of an OpenMetadata bot, from Settings > Bots (such as ingestion-bot; input hidden): ").strip()
    if not values.get("OM_UI_URL"):
        values["OM_UI_URL"] = url(prompt(
            "Where people browse OpenMetadata, for the user portal's link (optional,\n"
            "  such as https://metadata.example.com): ").strip())


def setup(root=ROOT, env=None, demo=False, ask=getpass.getpass, prompt=input, interactive=None):
    env = os.environ if env is None else env
    bridge = root / ".env.bridge"
    if not bridge.exists():
        raise SystemExit(
            "No .env.bridge. Register the extension with the platform first, from the platform directory:\n"
            "  uv run python -m scripts.setup --extension openmetadata --origin http://localhost:3011 "
            "--handshake extensions/openmetadata/.env.bridge --listing")
    handshake = read(bridge)
    if handshake.get("BRIDGE_CONTRACT") != "1":
        raise SystemExit("This OpenMetadata extension needs a Bridge v1 handshake file.")
    config = root / ".env"
    values = read(config) if config.exists() else {}
    for key, value in DEFAULTS.items():
        values.setdefault(key, value)
    values.update({name: url(env[name]) if name != "OM_JWT_TOKEN" else env[name]
                   for name in PASSTHROUGH if env.get(name)})
    if demo:
        # The local server's addresses come from compose.openmetadata.yaml; scripts.om_token writes the token.
        values.update({"COMPOSE_FILE": DEMO_COMPOSE, "OM_URL": "", "OM_UI_URL": ""})
    elif values.get("COMPOSE_FILE") != DEMO_COMPOSE:
        interactive = sys.stdin.isatty() if interactive is None else interactive
        if interactive and not (values["OM_URL"] and values["OM_JWT_TOKEN"]):
            ask_missing(values, ask, prompt)
    origin = urlsplit(handshake["EXTENSION_ORIGIN"])
    values["PLATFORM_NETWORK"] = handshake["PLATFORM_NETWORK"]
    values["OM_PORT"] = str(origin.port or (443 if origin.scheme == "https" else 80))
    content = "".join(f"{k}={v}\n" for k, v in values.items())
    if config.exists():
        config.unlink()
    with os.fdopen(os.open(config, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600), "w") as file:
        file.write("# Generated by scripts.setup; the bridge credentials stay in .env.bridge.\n" + content)
    # Relative names: the installer runs this in a container, where the absolute path means nothing.
    if values.get("COMPOSE_FILE") == DEMO_COMPOSE:
        print(".env: the local OpenMetadata of compose.openmetadata.yaml.")
    elif not values["OM_URL"] or not values["OM_JWT_TOKEN"]:
        print("Set OM_URL (the OpenMetadata API, such as https://metadata.example.com/api) and OM_JWT_TOKEN "
              "(the JWT of an OpenMetadata bot) in .env.")
    else:
        print(f".env: OpenMetadata at {values['OM_URL']}.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--demo", action="store_true", help="Use the local OpenMetadata of compose.openmetadata.yaml")
    setup(demo=parser.parse_args().demo)


if __name__ == "__main__":
    main()
